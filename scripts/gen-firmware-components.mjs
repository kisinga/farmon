// Embeds the vendored ESPHome external_components source (firmware/components/**)
// into a TS barrel the browser codegen can ship as GeneratedFile content (it runs
// in the browser with no fs). The real files under firmware/components/ are the
// source of truth — author/compile/test those; this barrel is a generated mirror.
//
//   Regenerate:  npm run gen:firmware-components
//   Drift guard: test/firmware-components.test.ts asserts this file is in sync.
import { readdirSync, readFileSync, writeFileSync, statSync } from 'node:fs';
import * as path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..');
const srcDir = path.join(root, 'firmware', 'components');
const outFile = path.join(root, 'src', 'lib', 'static', 'firmware-components.generated.ts');

/** Recursively list files under `dir`, returned as paths relative to `dir`, sorted.
 *  Python bytecode (__pycache__/*.pyc, created when esphome imports a component) is
 *  not source and must never ride into the barrel. */
function walk(dir, base = dir) {
  const out = [];
  for (const entry of readdirSync(dir)) {
    if (entry === '__pycache__') continue;
    const abs = path.join(dir, entry);
    if (statSync(abs).isDirectory()) out.push(...walk(abs, base));
    else if (!entry.endsWith('.pyc')) out.push(path.relative(base, abs));
  }
  return out.sort();
}

const files = walk(srcDir);
const entries = files
  .map((rel) => {
    const content = readFileSync(path.join(srcDir, rel), 'utf8');
    // POSIX separators in the emitted path — it becomes a bundle path on every OS.
    return `  { path: ${JSON.stringify(rel.split(path.sep).join('/'))}, content: ${JSON.stringify(content)} },`;
  })
  .join('\n');

const banner = `// AUTO-GENERATED by scripts/gen-firmware-components.mjs — DO NOT EDIT.
// Source of truth: firmware/components/**. Regenerate: npm run gen:firmware-components.`;

const body = `${banner}

export interface FirmwareComponentFile {
  /** Path under the bundle's external_components/ dir, e.g. "maji_coord/wire.cpp". */
  path: string;
  content: string;
}

export const FIRMWARE_COMPONENT_FILES: readonly FirmwareComponentFile[] = [
${entries}
];
`;

writeFileSync(outFile, body);
console.log(`Wrote ${files.length} file(s) to ${path.relative(root, outFile)}`);
