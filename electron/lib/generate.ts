export interface GeneratedFile {
  relativePath: string;
  description: string;
  content: string;
}

export { type GeneratorId, type SecretsMap, type GenerationMetadata } from './backends/types.js';

/** Convenience helper for tests — creates a valid GenerationMetadata with defaults. */
export function createTestMetadata(overrides?: Partial<GenerationMetadata>): GenerationMetadata {
  return {
    configSha: 'testsha000000000',
    version: 'testver1',
    siteId: 'test-site',
    controllerId: 'default',
    schemaVersion: 16,
    buildTimestamp: 0,
    appVersion: '0.0.0',
    ...overrides,
  };
}

export function generateDefaultSecrets(): SecretsMap {
  return {
    wifi_ssid: '',
    wifi_password: '',
    api_key: crypto.randomBytes(32).toString("base64"),
    ota_password: crypto.randomBytes(16).toString("hex"),
  };
}

function generateSecretsYaml(m: Manifest, secrets?: SecretsMap): string {
  const s = secrets ?? generateDefaultSecrets();
  return [
    `# ESPHome secrets for ${m.device.friendly_name}`,
    `# Generated by MajiFlow`,
    ``,
    `wifi_ssid: "${s.wifi_ssid}"`,
    `wifi_password: "${s.wifi_password}"`,
    `api_key: "${s.api_key}"`,
    `ota_password: "${s.ota_password}"`,
    ``,
  ].join("\n");
}

