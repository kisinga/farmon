/**
 * Returns the relative path prefix for everything a site generates.
 * `sites/{siteId}/...` is the single root for site-scoped artifacts:
 *   - `esphome/{deviceDir}/...`     — ESPHome firmware
 *   - `homeassistant/dashboards/{siteId}.yaml`        — site dashboard
 *   - `homeassistant/dashboards/dashboard.yaml`       — single-system convenience (tests)
 *   - `homeassistant/automations/{deviceDir}.yaml`    — per-device automations
 *   - `homeassistant/www/farm/{name}.{svg,meta.json}` — SCADA artifacts
 *   - `site-documentation.html`                       — generated docs
 *
 * Self-test artifacts live in a separate `selftest/{model}/` tree and bypass
 * this prefix entirely — they are not site-scoped.
 */
export function siteRoot(siteId: string): string {
  return `sites/${siteId}`;
}

export function generateEsphome(
  m: Manifest,
  board: BoardDef,
  siteId: string,
  secrets: SecretsMap | undefined,
  metadata: GenerationMetadata,
): GeneratedFile[] {
  const dir = m.device.directory ?? m.device.name;
  const deviceDir = `${siteRoot(siteId)}/esphome/${dir}`;
  const collected = collectEntityCodegen(m, board);

  const files: GeneratedFile[] = [
    {
      relativePath: `${deviceDir}/common/board.yaml`,
      description: `${board.label} board package (buses, battery, LED, diagnostics)`,
      content: generateBoardPackage(board, m.device.network),
    },
    {
      relativePath: `${deviceDir}/common/images/logo.svg`,
      description: "Logo image for OLED splash screen",
      content: LOGO_SVG,
    },
    {
      relativePath: `${deviceDir}/${dir}.yaml`,
      description: "Device config (substitutions, boot, OLED display)",
      content: generateDeviceYaml(board, m, collected, metadata),
    },
    {
      relativePath: `${deviceDir}/secrets.yaml`,
      description: "WiFi + API credentials",
      content: generateSecretsYaml(m, secrets),
    },
    {
      relativePath: `${deviceDir}/packages/control.yaml`,
      description: "State machine, API services, safety watchdog",
      content: generateControl(m),
    },
    {
      relativePath: `${deviceDir}/packages/routes.h`,
      description: "C++ route table + dispatch functions",
      content: generateRoutes(m),
    },
    {
      relativePath: `${deviceDir}/packages/hardware.yaml`,
      description: "Pump relay, valve switches + covers",
      content: generateHardware(m, collected),
    },
    {
      relativePath: `${deviceDir}/packages/sensors.yaml`,
      description: "Flow sensors, tank levels, calibration, state text",
      content: generateSensors(m, collected),
    },
    {
      relativePath: `${deviceDir}/packages/metadata.yaml`,
      description: "Fleet metadata sensors (SHA, version, build timestamp)",
      content: generateMetadataYaml(m, metadata),
    },
  ];

  return files;
}

export function generateSiteHA(
  siteId: string,
  siteName: string,
  systems: SiteDashboardSystem[],
  manifests: Map<string, Manifest>,
): GeneratedFile[] {
  const haRoot = `${siteRoot(siteId)}/homeassistant`;
  const files: GeneratedFile[] = [
    {
      relativePath: `${haRoot}/dashboards/${siteId}.yaml`,
      description: `HA dashboard — ${systems.length} controllers (overview + per-device tabs)`,
      content: generateSiteDashboard(siteName, systems),
    },
  ];

  for (const s of systems) {
    const m = manifests.get(s.systemId) ?? s.manifest;
    const dir = m.device.directory ?? m.device.name;
    const automationsContent = generateAutomations(m);
    if (automationsContent) {
      files.push({
        relativePath: `${haRoot}/automations/${dir}.yaml`,
        description: `HA automations — ${s.friendlyName}`,
        content: automationsContent,
      });
    }
  }

  return files;
}

/** Single-system convenience for tests. Produces ESPHome + per-device HA files. */
/**
 * Generate firmware files for a manifest + board using the specified backend.
 */
export function generateFirmware(
  generator: GeneratorId,
  manifest: Manifest,
  board: BoardDef,
  siteId: string,
  secrets: SecretsMap | undefined,
  metadata: GenerationMetadata,
): GeneratedFile[] {
  if (generator === 'esphome') {
    return generateEsphome(manifest, board, siteId, secrets, metadata);
  }
  throw new Error(`Unknown generator: ${generator}`);
}

export function generateAll(
  m: Manifest,
  board: BoardDef,
  siteId: string,
  secrets: SecretsMap | undefined,
  metadata: GenerationMetadata,
): GeneratedFile[] {
  const dir = m.device.directory ?? m.device.name;
  const haRoot = `${siteRoot(siteId)}/homeassistant`;
  const files = [...generateFirmware('esphome', m, board, siteId, secrets, metadata)];

  files.push({
    relativePath: `${haRoot}/dashboards/dashboard.yaml`,
    description: "HA dashboard with gauges, controls, settings",
    content: generateDashboard(m, board),
  });

  const automationsContent = generateAutomations(m);
  if (automationsContent) {
    files.push({
      relativePath: `${haRoot}/automations/${dir}.yaml`,
      description: "HA automations + system notifications",
      content: automationsContent,
    });
  }

  return files;
}
